// Interface language. The English strings in the code are the keys; ZH holds their translations.
// The choice is read synchronously (localStorage) so module-level labels are translated at import,
// and changing it reloads the page.

const STORAGE_KEY = "uiLanguage";
const LANGUAGES = ["en", "zh"];

export function browserLanguage() {
  return /^zh\b/i.test(navigator.language || "") ? "zh" : "en";
}

// "auto" (the default) follows the browser's language on every load; "en" and "zh" are fixed choices.
export function getLanguagePreference() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return LANGUAGES.includes(saved) ? saved : "auto";
  } catch {
    return "auto";
  }
}

export function resolveLanguage(preference) {
  return LANGUAGES.includes(preference) ? preference : browserLanguage();
}

export const uiLanguage = resolveLanguage(getLanguagePreference());

// Saves the preference. Returns true when the interface language changes, so the page has to reload.
export function setLanguagePreference(language) {
  if (![...LANGUAGES, "auto"].includes(language) || language === getLanguagePreference()) {
    return false;
  }
  try {
    if (language === "auto") {
      localStorage.removeItem(STORAGE_KEY);
    } else {
      localStorage.setItem(STORAGE_KEY, language);
    }
  } catch {
    return false;
  }
  return resolveLanguage(language) !== uiLanguage;
}

// Translations always go between Chinese and English, whatever the interface language: Chinese text
// becomes English and anything else becomes Simplified Chinese. Returns null when there's no text
// to judge by, so the prompt can leave the direction to the model.
export function translationTarget(text) {
  const letters = String(text ?? "").replace(/[\s\d\p{P}\p{S}]/gu, "");
  if (!letters) {
    return null;
  }
  const chinese = (letters.match(/[\u3400-\u9fff\uf900-\ufaff]/g) || []).length;
  return chinese / letters.length >= 0.3 ? "English" : "Simplified Chinese";
}

// The instruction for which way to translate, for a prompt.
export function translationDirection(text) {
  const target = translationTarget(text);
  return target
    ? `into ${target}`
    : "into English if it is written in Chinese, otherwise into Simplified Chinese";
}

// The language the assistant should write in when a prompt names one.
export function replyLanguageName() {
  if (uiLanguage === "zh") {
    return "Simplified Chinese";
  }
  try {
    const code = (navigator.language || "en").split("-")[0];
    return new Intl.DisplayNames(["en"], { type: "language" }).of(code) || "English";
  } catch {
    return "English";
  }
}

