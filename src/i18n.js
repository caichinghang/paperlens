// Interface language. The English strings in the code are the keys; ZH holds their translations.
// The choice is read synchronously (localStorage) so module-level labels are translated at import,
// and changing it reloads the page.

const STORAGE_KEY = "uiLanguage";
const LANGUAGES = ["en", "zh"];

function browserLanguage() {
  return /^zh\b/i.test(navigator.language || "") ? "zh" : "en";
}

// The first time the extension opens, the browser's language picks the interface language. That
// choice is saved, and from then on only the settings change it.
function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.includes(saved)) {
      return saved;
    }
    const detected = browserLanguage();
    localStorage.setItem(STORAGE_KEY, detected);
    return detected;
  } catch {
    return browserLanguage();
  }
}

export const uiLanguage = initialLanguage();

// Returns true when the language changed, so the page has to reload to show it.
export function setLanguagePreference(language) {
  if (!LANGUAGES.includes(language) || language === uiLanguage) {
    return false;
  }
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    return false;
  }
  return true;
}

// The language the assistant should write in when a prompt names one.
export function replyLanguageName() {
  if (uiLanguage === "zh") {
    return "Simplified Chinese";
  }
  try {
    const code = (navigator.language || "en").split("-")[0];
    return new Intl.DisplayNames(["en"], { type: "language" }).of(code) || "English";
  } catch {
    return "English";
  }
}

