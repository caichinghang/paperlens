export function t(text, params) {
  let result = uiLanguage === "zh" ? ZH[text] ?? text : text;
  if (params) {
    result = result.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }
  return result;
}

export function tn(count, one, other, params = {}) {
  return t(count === 1 ? one : other, { count, ...params });
}

const TRANSLATED_ATTRIBUTES = ["title", "aria-label", "placeholder"];

// Translates the static page: text nodes and labelling attributes whose whole text is a known string.
export function translateDom(root = document.body) {
  if (uiLanguage === "en") {
    return;
  }
  document.documentElement.lang = "zh-CN";
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && ZH[text]) {
      node.nodeValue = node.nodeValue.replace(text, ZH[text]);
    }
  }
  for (const attribute of TRANSLATED_ATTRIBUTES) {
    for (const element of root.querySelectorAll(`[${attribute}]`)) {
      const value = element.getAttribute(attribute);
      if (ZH[value]) {
        element.setAttribute(attribute, ZH[value]);
      }
    }
  }
}
